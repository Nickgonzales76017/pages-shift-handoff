import test from "node:test";
import assert from "node:assert/strict";
import {newWorkspace,summary,validate,transact,importTSV,exportHandoff,exportYaff,handoffCut} from "../site/continuity/core.mjs";
const fixture=()=>newWorkspace();
test("source-linked operational corpus is a scenario, never live dispatch",()=>{
 const w=fixture();assert.equal(validate(w),w);
 assert.equal(w.tasks.length,6);assert.equal(w.kind,"synthetic_operational_scenario");
 assert.ok(w.tasks.every(t=>t.source.startsWith("fixture://")));
 assert.deepEqual(summary(w),{total:6,open:6,critical:1,blocked:2,claimed:0,unreviewed:6,ready:1,verifiedResolved:0});
});
test("claim and lease are isolated, expiring and explicitly renewed",()=>{
 const w=fixture(),now=1760475600000,id="svc-supplier";
 const a=transact(w,"alex","claim",{taskId:id,now});
 assert.equal(a.tasks.find(x=>x.id===id).assignee,"alex");
 assert.equal(a.tasks.find(x=>x.id===id).leaseUntil,now+30*60_000);
 assert.throws(()=>transact(a,"morgan","claim",{taskId:id,now:now+1000}),/active claim/);
 assert.throws(()=>transact(a,"morgan","renew",{taskId:id,now:now+1000}),/Only the current claimant/);
 const renew=transact(a,"alex","renew",{taskId:id,now:now+1000});
 assert.ok(renew.tasks.find(x=>x.id===id).leaseUntil>now+30*60_000);
 const expired=transact(renew,"morgan","claim",{taskId:id,now:now+61*60_000});
 assert.equal(expired.tasks.find(x=>x.id===id).assignee,"morgan");
 assert.equal(w.revision,0,"no in-place mutation of source state");
});
test("critical incident needs claimant, blocker clearance, source receipt and independent review",()=>{
 let w=fixture(),id="svc-cooling",now=1760475600000;
 assert.throws(()=>transact(w,"alex","resolve",{taskId:id,receipt:"fixture://test/done",now}),/blocker/);
 w=transact(w,"alex","claim",{taskId:id,now});
 assert.throws(()=>transact(w,"alex","resolve",{taskId:id,receipt:"fixture://test/done",now}),/blocker/);
 w=transact(w,"alex","unblock",{taskId:id});
 assert.throws(()=>transact(w,"alex","resolve",{taskId:id,receipt:"fixture://test/done",now}),/review/);
 assert.throws(()=>transact(w,"alex","review",{taskId:id}),/Supervisor or incoming/);
 w=transact(w,"morgan","review",{taskId:id,note:"Verified source material for local handoff"});
 assert.throws(()=>transact(w,"alex","resolve",{taskId:id,receipt:"not-a-valid-source",now}),/completion receipt/);
 w=transact(w,"alex","resolve",{taskId:id,receipt:"fixture://technician/receipt-120",now});
 assert.equal(summary(w).critical,0);assert.equal(summary(w).verifiedResolved,1);
 assert.throws(()=>transact(w,"alex","claim",{taskId:id,now}),/Resolved work/);
});
test("incoming handoff requires exact revision and rejects stale cuts",()=>{
 let w=fixture();
 assert.throws(()=>transact(w,"morgan","prepare"),/outgoing/);
 w=transact(w,"alex","prepare");
 assert.equal(w.handoff.expectedRevision,w.revision);
 assert.ok(w.handoff.sourceCut.startsWith("bonfyre-shift-cut-v1"));
 assert.throws(()=>transact(w,"alex","accept"),/incoming/);
 let changed=transact(w,"alex","note",{taskId:"svc-access",note:"Updated the access record"});
 assert.throws(()=>transact(changed,"morgan","accept"),/stale/);
 assert.throws(()=>transact(changed,"alex","revoke"),/supervisor/);
 changed=transact(changed,"jordan","revoke");
 changed=transact(changed,"alex","prepare");
 const accepted=transact(changed,"morgan","accept");
 assert.equal(accepted.handoff.acceptedBy,"morgan");
 assert.equal(accepted.handoff.accepted,true);
 assert.throws(()=>transact(accepted,"alex","claim",{taskId:"svc-access"}),/Outgoing operator/);
 assert.throws(()=>transact(accepted,"alex","close"),/supervisor/);
 const closed=transact(accepted,"jordan","close");
 assert.equal(closed.closed,true);
 assert.throws(()=>transact(closed,"morgan","note",{taskId:"svc-access",note:"later"}),/closed/);
});
test("typed TSV batch refuses duplicates, bad sources and unsupported effects",()=>{
 const head="id\ttitle\tpriority\tkind\tsource\tdetail\n";
 const row="test-next\tCheck supply route\thigh\tvendor\thttps://example.org/vendor-source\tRequires supplier confirmation\n";
 const imported=importTSV(head+row,fixture());
 assert.equal(imported.tasks.length,7);assert.equal(imported.kind,"local_import");
 assert.equal(imported.tasks.at(-1).source,"https://example.org/vendor-source");
 assert.equal(imported.audit.at(-1).action,"imported");
 assert.throws(()=>importTSV(head+row,imported),/Invalid, repeated/);
 assert.throws(()=>importTSV(head+row.replace("https://example.org/vendor-source","javascript:alert(1)"),fixture()),/Invalid/);
 assert.throws(()=>importTSV("id\ttitle\nabc\ttest",fixture()),/Missing exact/);
});
test("source handoff contains open work, not invented completed work",()=>{
 let w=fixture();
 const cut=handoffCut(w),md=exportHandoff(w),yaff=exportYaff(w);
 assert.match(cut,/svc-cooling/);assert.match(md,/## Open work/);
 assert.match(md,/fixture:\/\/facilities\/site-4/);
 assert.match(md,/no live dispatch/);
 assert.match(yaff,/program operations-shift-continuity/);
 assert.match(yaff,/authority local-preview-only/);
 assert.doesNotMatch(yaff,/mission accepted/);
 w=transact(w,"alex","note",{taskId:"svc-access",note:"New access item"});
 assert.notEqual(handoffCut(w),cut);
});
